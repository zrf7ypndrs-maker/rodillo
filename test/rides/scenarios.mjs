// A script is a list of [second, what, do]: at that second of the ride (wall clock, not ride time) `do` runs before
// the tick, with { s: the Session, tr: the trainer, hr: the strap, stall(dt): make the next tick that long }.
// The `what` text goes in the recording, so a difference can be read as "after: skip".
